CREATE DATABASE IF NOT EXISTS snapmoment_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE snapmoment_db;
CREATE TABLE IF NOT EXISTS visitors (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 visitor_code VARCHAR(20) NOT NULL UNIQUE,
 visitor_token CHAR(64) NOT NULL UNIQUE,
 name VARCHAR(100) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 last_seen_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS photos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 visitor_id BIGINT UNSIGNED NOT NULL,
 photo_path VARCHAR(255) NOT NULL,
 original_name VARCHAR(255) NOT NULL,
 mime_type VARCHAR(50) NOT NULL,
 file_size INT UNSIGNED NOT NULL,
 status ENUM('pending','approved','rejected') NOT NULL DEFAULT 'pending',
 uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 reviewed_at TIMESTAMP NULL DEFAULT NULL,
 KEY idx_photos_visitor(visitor_id),
 KEY idx_photos_status(status),
 CONSTRAINT fk_photos_visitor FOREIGN KEY(visitor_id) REFERENCES visitors(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS admins (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(60) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
